"""Framework coverage: which OWASP LLM, OWASP Agentic (ASI) and MITRE ATLAS ids each surface carries.

Built from the loaded technique library and scenario files, never typed by hand, so the README table
(`render_coverage_table`) cannot drift from what the library is actually tagged with: a test rebuilds
it and compares it to the README.
"""

from __future__ import annotations

import re
from collections.abc import Callable, Iterable

from .agent_a2a import load_a2a_scenarios
from .agent_disclosure import load_disclosure_scenarios
from .agent_memory import load_memory_scenarios
from .agent_misinfo import load_misinfo_scenarios
from .agent_privilege import load_privilege_scenarios
from .agent_rag import load_rag_scenarios
from .agent_scenarios import load_scenarios
from .agent_toolabuse import load_toolabuse_scenarios
from .attacks import load_library
from .config import ATLAS_RELEASE, CATEGORIES, VALID_ATLAS

# Agent surfaces in the order the README lists them, keyed by the command that runs each.
SCENARIO_SURFACES: tuple[tuple[str, Callable[[], list]], ...] = (
    ("agent-run", load_scenarios),
    ("tool-abuse-run", load_toolabuse_scenarios),
    ("privilege-run", load_privilege_scenarios),
    ("disclosure-run", load_disclosure_scenarios),
    ("misinfo-run", load_misinfo_scenarios),
    ("memory-run", load_memory_scenarios),
    ("rag-run", load_rag_scenarios),
    ("a2a-run", load_a2a_scenarios),
)

COVERAGE_START = "<!-- framework-coverage:start (generated by iago.frameworks; do not edit) -->"
COVERAGE_END = "<!-- framework-coverage:end -->"


def _ids(tags: Iterable[str | None]) -> list[str]:
    """Distinct leading ids ("LLM01: Prompt Injection" -> "LLM01"), sorted."""
    return sorted({t.split(":", 1)[0].strip() for t in tags if t and t.strip()})


def _owasp_ids(tags: Iterable[str | None]) -> list[str]:
    """Every LLMnn id named anywhere in an owasp tag. Scenario owasp tags are free text
    ("LLM01 / ASI01", "n/a — positive control"), so take the ids, not the leading segment."""
    return sorted({m for t in tags if t for m in re.findall(r"\bLLM\d\d\b", t)})


def _cell(ids: list[str], *, atlas: bool = False) -> str:
    if not ids:
        return "—"
    if atlas:
        return "<br>".join(f"`{i}` {VALID_ATLAS[i]}" for i in ids)
    return ", ".join(f"`{i}`" for i in ids)


def coverage_rows() -> list[tuple[str, str, str, str]]:
    """(surface, OWASP LLM, OWASP Agentic, MITRE ATLAS) for every technique category, then every
    agent surface, in library order. A surface with no tag of a kind shows a dash."""
    rows = []
    lib = load_library()
    for cat in CATEGORIES:
        techs = [t for t in lib if t.category == cat]
        if not techs:
            continue
        rows.append((f"`{cat}` techniques",
                     _cell(_owasp_ids(t.owasp for t in techs)),
                     _cell(_ids(t.asi for t in techs)),
                     _cell(_ids(t.atlas for t in techs), atlas=True)))
    for command, load in SCENARIO_SURFACES:
        scens = load()
        rows.append((f"`{command}` scenarios",
                     _cell(_owasp_ids(getattr(s, "owasp", None) for s in scens)),
                     _cell(_ids(s.asi for s in scens)),
                     _cell(_ids(s.atlas for s in scens), atlas=True)))
    return rows


def render_coverage_table() -> str:
    """The README block between COVERAGE_START and COVERAGE_END, markers included."""
    lines = [COVERAGE_START,
             "",
             f"| Surface | OWASP LLM (2025) | OWASP Agentic (2026) | MITRE ATLAS ({ATLAS_RELEASE}) |",
             "|---|---|---|---|"]
    lines += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in coverage_rows()]
    lines += ["", COVERAGE_END]
    return "\n".join(lines)


if __name__ == "__main__":
    print(render_coverage_table())
