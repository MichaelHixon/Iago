"""Framework coverage: which OWASP LLM, OWASP Agentic (ASI) and MITRE ATLAS ids each surface carries.

Built from the loaded technique library and the agent surface registry, never typed by hand, so the
README table (`render_coverage_table`) cannot drift from what the library is actually tagged with: a
test rebuilds it and compares it to the README.
"""

from __future__ import annotations

import re
from collections.abc import Iterable

from .attacks import load_library
from .campaign import SURFACES
from .config import ATLAS_RELEASE, CATEGORIES, VALID_ATLAS, tag_id

COVERAGE_START = "<!-- framework-coverage:start (generated by iago.frameworks; do not edit) -->"
COVERAGE_END = "<!-- framework-coverage:end -->"


def _ids(tags: Iterable[str | None]) -> list[str]:
    """Distinct leading ids of ASI / ATLAS tags, parsed the way the validators parse them."""
    return sorted({tag_id(t) for t in tags if t and t.strip()})


def _owasp_ids(tags: Iterable[str | None]) -> list[str]:
    """Every LLMnn id named anywhere in an owasp tag. Scenario owasp tags are free text
    ("LLM01 / ASI01", "n/a — positive control"), so take the ids, not the leading segment."""
    return sorted({m for t in tags if t for m in re.findall(r"\bLLM\d\d\b", t)})


def _cell(ids: list[str], *, atlas: bool = False) -> str:
    if not ids:
        return "—"
    if atlas:
        return "<br>".join(f"`{i}` {VALID_ATLAS[i]}" for i in ids)
    return ", ".join(f"`{i}`" for i in ids)


def _row(surface: str, records: list) -> tuple[str, str, str, str]:
    return (surface,
            _cell(_owasp_ids(r.owasp for r in records)),
            _cell(_ids(r.asi for r in records)),
            _cell(_ids(r.atlas for r in records), atlas=True))


def coverage_rows() -> list[tuple[str, str, str, str]]:
    """(surface, OWASP LLM, OWASP Agentic, MITRE ATLAS) for every technique category, then every
    registered agent surface, in library / registry order. A surface with no tag of a kind shows a dash."""
    lib = load_library()
    rows = [_row(f"`{cat}` techniques", techs)
            for cat in CATEGORIES if (techs := [t for t in lib if t.category == cat])]
    rows += [_row(f"`{spec.command}` scenarios", spec.scenarios()) for spec in SURFACES.values()]
    return rows


def render_coverage_table() -> str:
    """The README block between COVERAGE_START and COVERAGE_END, markers included."""
    lines = [COVERAGE_START,
             "",
             f"| Surface | OWASP LLM (2025) | OWASP Agentic (2026) | MITRE ATLAS ({ATLAS_RELEASE}) |",
             "|---|---|---|---|"]
    lines += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in coverage_rows()]
    lines += ["", COVERAGE_END]
    return "\n".join(lines)


if __name__ == "__main__":
    print(render_coverage_table())
